const seedDatabase = async () => {
  try {
    const mongoUri = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/cafe_ordering';
    await mongoose.connect(mongoUri);
    console.log(`[Seed] Connected to MongoDB at ${mongoUri}`);

    const deleteResult = await MenuItem.deleteMany({});
    console.log(`[Seed] Cleared ${deleteResult.deletedCount} existing menu items.`);

    const createdItems = await MenuItem.insertMany(sampleMenuItems);
    console.log(`[Seed] Successfully seeded ${createdItems.length} Affordable Cafe items with exact images!`);

    await mongoose.connection.close();
    console.log('[Seed] Database connection closed.');
    process.exit(0);
  } catch (error) {
    console.error('[Seed Error] Failed to seed database:', error);
    process.exit(1);
  }
};

seedDatabase();
